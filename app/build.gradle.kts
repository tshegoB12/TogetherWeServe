// Release signing: create keystore.properties (git-ignored) in the project root with
// storeFile, storePassword, keyAlias, keyPassword. Without it, the release build is
// produced unsigned (this is what GitHub Actions does).
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) FileInputStream(keystorePropsFile).use { load(it) }
}

android {
    namespace = "com.togetherweserve.app"
    compileSdk = 34

    defaultConfig {
